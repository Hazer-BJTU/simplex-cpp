#pragma once

#include <cstddef>
#include <cstdint>
#include <filesystem>
#include <string>
#include <string_view>
#include <vector>

#include "fileio/replace_existing.hpp"
#include "fileio/streaming.hpp"

namespace fileio {

/**
 * Observer for the source bytes re-read while a replacement is verified.
 *
 * The verification pass learns the original bytes one chunk at a time; a
 * caller that needs row coordinates or bounded preview material can collect
 * them here instead of re-reading the file itself. Only the verified prefix and
 * suffix are reported, never the replaced span, and offsets are absolute source
 * positions in increasing order.
 */
class SourceObserver {
public:
    virtual ~SourceObserver() = default;
    virtual void observe(std::uintmax_t offset, std::string_view bytes) = 0;
};

/**
 * One streaming replacement transaction for an existing regular file.
 *
 * Construction applies the editable-file policy (single-link regular file,
 * no set-id bits, no final symlink) and records the opened identity; the
 * private mode-0600 candidate is created on first use, so a scan that finds no
 * match never creates one. The caller then scans the source through
 * next_source(). Bytes before the match are not written: copy_prefix() copies
 * them straight from the source once the match is known, and write() appends
 * the replacement and then the suffix. publish() verifies the still-unchanged
 * source and atomically replaces the destination; every other exit discards the
 * candidate.
 *
 * Memory stays at one fixed buffer plus caller state. The source is read at
 * most twice (initial scan, publication check) and the candidate once, which
 * keeps a successful edit within the documented scan budget; copy_prefix() uses
 * a kernel-side copy where the platform supports one. Failures before rename
 * throw std::system_error, ReplaceConflict or std::length_error and never
 * modify the destination; a directory-sync failure after rename throws
 * AtomicWriteError with published() set. External writers that ignore this
 * protocol can still race after the final check.
 */
class StagedReplacement {
public:
    /** Open the source; create the candidate lazily; see the class contract. */
    explicit StagedReplacement(
        const std::filesystem::path& path,
        std::size_t buffer_bytes = kStreamBufferBytes);

    StagedReplacement(StagedReplacement&& other) noexcept;
    StagedReplacement& operator=(StagedReplacement&& other) noexcept;
    ~StagedReplacement();

    StagedReplacement(const StagedReplacement&) = delete;
    StagedReplacement& operator=(const StagedReplacement&) = delete;

    /** Next source bytes; empty at EOF. Borrowed until the next call. */
    [[nodiscard]] std::string_view next_source();

    /** Restart the scan from the beginning; resets source_bytes().
     *
     * A second pass is only meaningful before publish(), which owns the
     * unchanged-source check: it is how a caller collects preview material for
     * an edit that publishes nothing.
     */
    void restart_source();

    /** Source bytes observed since the last restart. */
    [[nodiscard]] std::uintmax_t source_bytes() const noexcept;

    /** Metadata captured when the source was opened. */
    [[nodiscard]] const FileIdentity& identity() const noexcept;

    /** Candidate bytes written so far. */
    [[nodiscard]] std::uintmax_t candidate_bytes() const noexcept;

    /**
     * Copy the first `bytes` bytes of the source into the candidate.
     *
     * Called once the match is known, so the untouched prefix is copied rather
     * than replayed during the scan. Must be the first candidate write.
     */
    void copy_prefix(std::uintmax_t bytes);

    /** Append generated bytes to the private candidate. */
    void write(std::string_view bytes);

    /**
     * Verify the unchanged source and publish the candidate.
     *
     * `match_byte` is the source offset of the replaced region; `matched_source`
     * is the exact original span that the candidate's replacement region
     * occupies. The comparison rebuilds the original from the candidate, so no
     * whole-file snapshot is retained. When `observer` is set, every verified
     * source byte outside the span is reported to it. Throws ReplaceConflict
     * when the source changed, AtomicWriteError when publication succeeded but
     * the directory could not be synchronized, or std::system_error before
     * publication.
     */
    void publish(std::uintmax_t match_byte, std::string_view matched_source,
                 SourceObserver* observer = nullptr);

    /** Drop the candidate and never touch the destination. */
    void discard() noexcept;

private:
    void ensure_candidate();
    void finish_candidate();
    void confirm_source_unchanged(int descriptor) const;
    void verify_against_source(
        std::uintmax_t match_byte, std::string_view matched_source,
        SourceObserver* observer);

    std::filesystem::path destination_;
    std::string temporary_path_;
    FileIdentity identity_;
    std::vector<char> buffer_;
    std::uintmax_t source_bytes_ = 0;
    std::uintmax_t candidate_bytes_ = 0;
    int source_ = -1;
    int candidate_ = -1;
    int directory_ = -1;
    bool consumed_ = false;
};

} // namespace fileio
