#pragma once

/**
 * @file protocol/manifest.hpp
 * @brief The published contract document, its JSON Schema view and fingerprint.
 *
 * Three artifacts come out of the same compiled descriptors:
 *
 *   - `canonical_contract()`: structure only — names, kinds, presence rules,
 *     enum spellings, record references and the event registry. Explanations are
 *     excluded on purpose, so editing a sentence cannot change the fingerprint.
 *   - `manifest()`: the published document. Canonical structure, English
 *     summaries, extension policies, JSON Schema definitions and the fingerprint.
 *   - `fingerprint()`: lowercase hex SHA-256 of the canonical contract.
 *
 * The fingerprint certifies the structural contract and nothing else. Ordering,
 * delivery and backpressure, cancellation, confirmation deadlines, security
 * judgement and storage atomicity remain prose requirements; the manifest says
 * so explicitly so a matching fingerprint is never read as a compatibility
 * promise.
 *
 * `schemas/worker-protocol.json` is generated by `protocol_manifest_export` and
 * committed for review and for consumers that cannot build C++. It is never an
 * independent source of truth: `test_protocol_manifest` fails when it is stale.
 */

#include "protocol/wire.hpp"

#include <span>
#include <string>
#include <string_view>

namespace protocol {

/** Format identifier of the manifest document itself, not of the wire protocol. */
inline constexpr std::string_view manifest_format = "simplex.worker-protocol/1";

/** Protocol name reported by the manifest. */
inline constexpr std::string_view protocol_name = "simplex-worker";

/** Every record the contract describes, ordered by name. */
std::span<const RecordDescriptor* const> record_registry();

/** Every closed vocabulary the contract publishes, ordered by name. */
std::span<const EnumDescriptor* const> enum_registry();

/** Structural document that the fingerprint covers. */
Json canonical_contract();

/** Published manifest: canonical structure plus prose, schema and fingerprint. */
Json manifest();

/** JSON Schema 2020-12 view over the same definitions. */
Json json_schema();

/** Lowercase hex SHA-256 of `canonical_contract()`. */
std::string fingerprint();

} // namespace protocol
